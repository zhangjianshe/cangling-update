const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync(require('node:path').join(__dirname, '../src/assets/index.html'), 'utf8');
for (const match of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
const dom = new Map();
const el = () => ({ innerHTML: '', hidden: true, classList: { add() {} } });
for (const key of ['#dialog', '#dialog-title', '#dialog-modal']) dom.set(key, el());
const body = el();
Object.defineProperty(body, 'innerHTML', { set() { dom.set('#accelerator-report', el()); } });
dom.set('#dialog-body', body);
let request;
const context = vm.createContext({ Date, Number, $: key => dom.get(key), closeDialog() { dom.delete('#accelerator-report'); dom.get('#dialog').hidden = true; }, setDialogAction() {}, api() { return new Promise((resolve, reject) => { request = { resolve, reject }; }); }, esc(value) { return String(value == null ? '' : value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c])); } });
const start = html.indexOf('    function deviceCheckRows(');
vm.runInContext(html.slice(start, html.indexOf('    async function renderK3s()', start)), context);
const host = { hostname: '<img src=x onerror=1>', observedAt: new Date().toISOString(), devices: [{ vendor: 'Other', name: '<script>alert(1)</script>', pciAddress: '0000:01:00.0' }], checks: [{ stage: 'driver', status: 'unknown', message: '未验证' }] };
const report = { observedAt: 'now', nodes: [{ name: '<node>', nodeInfo: {}, resources: [{ name: 'vendor.test/partition', capacity: 8, allocatable: 8, requested: null, free: null }], checks: host.checks }], components: [{ name: 'operator', namespace: 'gpu', phase: 'Running', status: 'error', message: 'ImagePullBackOff <script>', images: ['vendor/image:1'] }], warnings: ['<img onerror=1>'], runtimeClasses: [] };
assert.match(context.hostDeviceReportHtml(null), /尚未采集/);
const h = context.hostDeviceReportHtml(host);
assert.match(h, /&lt;script&gt;/); assert.doesNotMatch(h, /<script>/); assert.match(h, /未验证/);
const r = context.clusterDeviceReportHtml(report);
assert.match(r, /vendor.test\/partition/); assert.match(r, /未采集/); assert.match(r, /ImagePullBackOff &lt;script&gt;/); assert.doesNotMatch(r, /<img onerror/);
assert.match(r, /不是物理卡数或实际利用率/);
const hygon = { hostname: 'np4-master', observedAt: new Date().toISOString(), devices: Array.from({ length: 6 }, (_, i) => ({ vendor: 'Hygon', name: 'BW100', pciAddress: `0000:${i}:00.0`, memoryMiB: 65520, driver: 'hycu', driverVersion: '6.3.30-V1.4.1a' })) };
assert.match(context.hostDeviceReportHtml(hygon), /已识别物理设备：6 个/);
const hygonCluster = context.clusterDeviceReportHtml({ nodes: [{ name: 'np4-master', hostDiagnostics: hygon, resources: [{ name: 'hygon.com/dcunum', capacity: 24, allocatable: 24, requested: 0, free: 24 }] }] });
assert.match(hygonCluster, /已识别物理设备：6 个/);
assert.match(hygonCluster, /hygon.com\/dcunum/);
assert.match(hygonCluster, />24</);
assert.match(context.physicalDeviceSummary({ devices: [], observedAt: new Date().toISOString() }), /未确认/);
assert.match(context.physicalDeviceSummary({ ...hygon, observedAt: '2000-01-01' }), /已过期/);
assert.match(context.physicalDeviceSummary(null), /未采集/);

(async () => {
  const staleRequest = context.openDeviceDiagnostics('cluster');
  const oldRoot = dom.get('#accelerator-report');
  context.closeDialog();
  request.resolve(report); await staleRequest;
  assert.equal(oldRoot.innerHTML, '');
  const failure = context.openDeviceDiagnostics('cluster');
  request.reject(new Error('Forbidden <script>')); await failure;
  assert.match(dom.get('#accelerator-report').innerHTML, /Forbidden &lt;script&gt;/);
  assert.match(html, /id="accelerator-report" style="[^"]*overflow:auto/);
  assert.match(html, /id="k3s-devices"/); assert.match(html, /data-host-devices=/);
  console.log('Accelerator UI: scripts parse, unknown and stale data remain explicit, credentials are not requested, untrusted output is escaped, closed dialogs ignore delayed responses.');
})().catch(e => { console.error(e); process.exitCode = 1; });
